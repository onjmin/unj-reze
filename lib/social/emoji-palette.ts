/** 手書きの表なので同じ絵文字が重複しうる。カテゴリ内で重複を落とす（React の key 衝突と二重表示を防ぐ）。 */
function dedupe(categories: EmojiCategory[]): EmojiCategory[] {
	return categories.map((c) => ({ ...c, emojis: Array.from(new Set(c.emojis)) }));
}

const RECENT_KEY = "contentPicker.recentEmojis";
const RECENT_MAX = 24;

/** 最近使った絵文字（新しい順）。localStorage が使えない環境では空配列。 */
export function loadRecentEmojis(): string[] {
	try {
		const raw = localStorage.getItem(RECENT_KEY);
		if (!raw) return [];
		const arr = JSON.parse(raw);
		return Array.isArray(arr) ? arr.filter((s) => typeof s === "string") : [];
	} catch {
		return [];
	}
}

export function pushRecentEmoji(emoji: string): string[] {
	const next = [emoji, ...loadRecentEmojis().filter((e) => e !== emoji)].slice(0, RECENT_MAX);
	try {
		localStorage.setItem(RECENT_KEY, JSON.stringify(next));
	} catch {
		// 保存できなくても選択自体は成立するので黙って続ける
	}
	return next;
}

/** 参照文字列 `emoji:X` を組み立てる。 */
export function buildEmojiRef(emoji: string): string {
	return `emoji:${emoji}`;
}
